/// RFC 7807 Problem Details error
#[derive(Debug, Clone, serde::Serialize, serde::Deserialize, utoipa::ToSchema)]
pub struct ProblemDetails {
    /// A URI reference that identifies the problem type (RFC 9457 `type`)
    #[serde(rename = "type", skip_serializing_if = "Option::is_none")]
    pub type_uri: Option<String>,
    /// A short, human-readable summary of the problem type
    pub title: String,
    /// The HTTP status code generated by the origin server
    pub status: u16,
    /// A human-readable explanation specific to this occurrence
    #[serde(skip_serializing_if = "Option::is_none")]
    pub detail: Option<String>,
    /// A URI reference that identifies the specific occurrence of the problem
    #[serde(skip_serializing_if = "Option::is_none")]
    pub instance: Option<String>,
    /// Additional problem-specific fields
    #[serde(flatten)]
    pub extensions: std::collections::HashMap<String, serde_json::Value>,
}

impl ProblemDetails {
    pub fn new(status: u16, title: &str) -> Self {
        Self {
            type_uri: None,
            title: title.to_string(),
            status,
            detail: None,
            instance: None,
            extensions: std::collections::HashMap::new(),
        }
    }

    pub fn with_detail(mut self, detail: &str) -> Self {
        self.detail = Some(detail.to_string());
        self
    }

    pub fn with_instance(mut self, instance: &str) -> Self {
        self.instance = Some(instance.to_string());
        self
    }

    pub fn with_type(mut self, type_uri: &str) -> Self {
        self.type_uri = Some(type_uri.to_string());
        self
    }

    #[allow(dead_code)]
    pub fn with_extension(mut self, key: &str, value: serde_json::Value) -> Self {
        self.extensions.insert(key.to_string(), value);
        self
    }

    pub fn with_extensions(
        mut self,
        ext: std::collections::HashMap<String, serde_json::Value>,
    ) -> Self {
        self.extensions = ext;
        self
    }
}

/// Validation error codes for precise error identification
#[derive(
    Debug, Clone, Copy, PartialEq, Eq, serde::Serialize, serde::Deserialize, utoipa::ToSchema,
)]
#[serde(rename_all = "snake_case")]
pub enum ValidationErrorCode {
    /// Zone name is not a valid DNS name
    InvalidZoneName,
    /// Record name is not a valid relative DNS name
    InvalidRecordName,
    /// Record type is not supported
    UnsupportedRecordType,
    /// IPv4 address format is invalid
    InvalidIpv4Address,
    /// IPv6 address format is invalid
    InvalidIpv6Address,
    /// CNAME target is not a valid DNS name
    InvalidCnameTarget,
    /// MX record format is invalid (priority + target)
    InvalidMxRecord,
    /// NS record target is not a valid DNS name
    InvalidNsTarget,
    /// TXT record value is invalid
    InvalidTxtValue,
    /// SRV record format is invalid (priority weight port target)
    InvalidSrvRecord,
    /// CAA record format is invalid
    InvalidCaaRecord,
    /// Zone file failed named-checkzone validation
    ZoneValidationFailed,
    /// named-checkzone exceeded its execution deadline
    ZoneValidationTimeout,
    /// Record value contains invalid characters
    InvalidCharacters,
    /// Label too long (>63 chars) or name too long (>253 chars)
    LabelTooLong,
    /// Empty label or name
    EmptyLabel,
    /// Invalid TTL value
    InvalidTtl,
    /// Zone payload exceeds configured resource limits
    ResourceLimitExceeded,
    /// Records conflict at the same owner name
    ConflictingRecords,
}

impl ValidationErrorCode {
    #[allow(dead_code)]
    pub fn title(&self) -> &'static str {
        match self {
            Self::InvalidZoneName => "Invalid Zone Name",
            Self::InvalidRecordName => "Invalid Record Name",
            Self::UnsupportedRecordType => "Unsupported Record Type",
            Self::InvalidIpv4Address => "Invalid IPv4 Address",
            Self::InvalidIpv6Address => "Invalid IPv6 Address",
            Self::InvalidCnameTarget => "Invalid CNAME Target",
            Self::InvalidMxRecord => "Invalid MX Record",
            Self::InvalidNsTarget => "Invalid NS Target",
            Self::InvalidTxtValue => "Invalid TXT Value",
            Self::InvalidSrvRecord => "Invalid SRV Record",
            Self::InvalidCaaRecord => "Invalid CAA Record",
            Self::ZoneValidationFailed => "Zone Validation Failed",
            Self::ZoneValidationTimeout => "Zone Validation Timed Out",
            Self::InvalidCharacters => "Invalid Characters",
            Self::LabelTooLong => "Label Too Long",
            Self::EmptyLabel => "Empty Label",
            Self::InvalidTtl => "Invalid TTL",
            Self::ResourceLimitExceeded => "Payload Limit Exceeded",
            Self::ConflictingRecords => "Conflicting DNS Records",
        }
    }

    pub fn status_code(&self) -> u16 {
        match self {
            Self::ResourceLimitExceeded => 413,
            Self::ConflictingRecords => 422,
            Self::UnsupportedRecordType => 400,
            Self::ZoneValidationFailed => 422,
            Self::ZoneValidationTimeout => 503,
            _ => 400,
        }
    }
}

/// Validation error with code and context
#[derive(Debug, Error, Clone, serde::Serialize, serde::Deserialize)]
#[error("{code:?}: {message}")]
pub struct ValidationError {
    pub code: ValidationErrorCode,
    pub message: String,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub field: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub value: Option<String>,
}

impl ValidationError {
    pub fn new(code: ValidationErrorCode, message: impl Into<String>) -> Self {
        Self {
            code,
            message: message.into(),
            field: None,
            value: None,
        }
    }

    pub fn with_field(mut self, field: &str) -> Self {
        self.field = Some(field.to_string());
        self
    }

    pub fn with_value(mut self, value: &str) -> Self {
        self.value = Some(value.to_string());
        self
    }

    #[allow(dead_code)]
    pub fn to_problem_details(&self, instance: Option<&str>) -> ProblemDetails {
        let mut ext = std::collections::HashMap::new();
        ext.insert(
            "error_code".to_string(),
            serde_json::to_value(self.code).unwrap(),
        );
        if let Some(ref field) = self.field {
            ext.insert(
                "field".to_string(),
                serde_json::Value::String(field.clone()),
            );
        }
        if let Some(ref value) = self.value {
            ext.insert(
                "value".to_string(),
                serde_json::Value::String(value.clone()),
            );
        }

        ProblemDetails::new(self.code.status_code(), self.code.title())
            .with_detail(&self.message)
            .with_instance(instance.unwrap_or(""))
            .with_extensions(ext)
    }
}

/// Supported DNS record types
pub const SUPPORTED_RECORD_TYPES: &[&str] =
    &["A", "AAAA", "CNAME", "MX", "NS", "TXT", "SRV", "CAA"];

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ValidatedRecord {
    pub name: Option<Name>,
    pub data: ValidatedRData,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum ValidatedRData {
    A(Ipv4Addr),
    Aaaa(Ipv6Addr),
    Cname(Name),
    Mx {
        priority: u16,
        target: Name,
    },
    Ns(Name),
    Txt(Vec<u8>),
    Srv {
        priority: u16,
        weight: u16,
        port: u16,
        target: Name,
    },
    Caa {
        flags: u8,
        tag: String,
        value: Vec<u8>,
    },
}

/// Encode raw DNS character-string bytes as a safe master-file string.
pub fn quote_master_file_string(bytes: &[u8]) -> String {
    let mut output = String::with_capacity(bytes.len() + 2);
    output.push('"');
    for byte in bytes {
        match *byte {
            b'"' | b'\\' => {
                output.push('\\');
                output.push(*byte as char);
            }
            0x20..=0x7e => output.push(*byte as char),
            other => write!(&mut output, "\\{:03}", other).expect("writing to String cannot fail"),
        }
    }
    output.push('"');
    output
}

/// Validates a DNS name (absolute or relative)
/// Returns the normalized name (lowercase, no trailing dot for relative names)
pub fn validate_dns_name(name: &str, allow_absolute: bool) -> Result<String, ValidationError> {
    if name.is_empty() {
        return Err(ValidationError::new(
            ValidationErrorCode::EmptyLabel,
            "DNS name cannot be empty",
        ));
    }

    let trimmed = name.trim();
    if trimmed.is_empty() || trimmed == "." {
        return Err(ValidationError::new(
            ValidationErrorCode::EmptyLabel,
            "DNS name cannot be empty or the root name",
        ));
    }

    let is_absolute = trimmed.ends_with('.');
    if is_absolute && !allow_absolute {
        return Err(ValidationError::new(
            ValidationErrorCode::InvalidCharacters,
            "Absolute DNS names (ending with .) not allowed for record names",
        )
        .with_field("name")
        .with_value(trimmed));
    }

    let parsed = Name::from_str_relaxed(trimmed).map_err(|error| {
        ValidationError::new(
            ValidationErrorCode::InvalidCharacters,
            format!("Invalid DNS name: {}", error),
        )
        .with_field("name")
        .with_value(trimmed)
    })?;

    if parsed.len() > 255 {
        return Err(ValidationError::new(
            ValidationErrorCode::LabelTooLong,
            format!(
                "DNS name exceeds 255 wire-format bytes (got {})",
                parsed.len()
            ),
        )
        .with_field("name")
        .with_value(trimmed));
    }

    let normalized = parsed.to_ascii().to_lowercase();
    if is_absolute && !normalized.ends_with('.') {
        return Err(ValidationError::new(
            ValidationErrorCode::InvalidZoneName,
            "Absolute DNS name must end with a dot",
        )
        .with_field("name")
        .with_value(trimmed));
    }
    Ok(normalized)
}

/// Validates a zone name (must be absolute DNS name)
pub fn validate_zone_name(zone: &str) -> Result<String, ValidationError> {
    let normalized = validate_dns_name(zone, true)?;
    if normalized
        .trim_end_matches('.')
        .split('.')
        .any(|label| label.starts_with('-') || label.ends_with('-'))
    {
        return Err(ValidationError::new(
            ValidationErrorCode::InvalidCharacters,
            "Zone labels cannot start or end with a hyphen",
        )
        .with_field("name")
        .with_value(zone));
    }
    if !normalized.ends_with('.') {
        Ok(format!("{}.", normalized))
    } else {
        Ok(normalized)
    }
}

/// Validates a record name (relative DNS name, no trailing dot)
pub fn validate_record_name(name: &str) -> Result<String, ValidationError> {
    if name.trim() == "@" {
        return Ok("@".to_string());
    }

    validate_dns_name(name, false)
}

fn validated_name(value: &str) -> Result<Name, ValidationError> {
    Name::from_str_relaxed(value).map_err(|error| {
        ValidationError::new(
            ValidationErrorCode::InvalidCharacters,
            format!("Invalid DNS name: {}", error),
        )
        .with_field("value")
        .with_value(value)
    })
}

/// Validates an IPv4 address
pub fn validate_ipv4(addr: &str) -> Result<Ipv4Addr, ValidationError> {
    addr.parse().map_err(|_| {
        ValidationError::new(
            ValidationErrorCode::InvalidIpv4Address,
            format!("'{}' is not a valid IPv4 address", addr),
        )
        .with_field("value")
        .with_value(addr)
    })
}

/// Validates an IPv6 address
pub fn validate_ipv6(addr: &str) -> Result<Ipv6Addr, ValidationError> {
    addr.parse().map_err(|_| {
        ValidationError::new(
            ValidationErrorCode::InvalidIpv6Address,
            format!("'{}' is not a valid IPv6 address", addr),
        )
        .with_field("value")
        .with_value(addr)
    })
}

/// Validates a CNAME target (must be absolute DNS name)
pub fn validate_cname_target(target: &str) -> Result<String, ValidationError> {
    validate_dns_name(target, true)
}

/// Validates an MX record value (priority + target)
pub fn validate_mx_value(value: &str) -> Result<(u16, String), ValidationError> {
    let parts: Vec<&str> = value.split_whitespace().collect();
    if parts.len() != 2 {
        return Err(ValidationError::new(
            ValidationErrorCode::InvalidMxRecord,
            "MX record must have format: 'priority target' (e.g., '10 mail.example.com')",
        )
        .with_field("value")
        .with_value(value));
    }

    let priority = parts[0].parse::<u16>().map_err(|_| {
        ValidationError::new(
            ValidationErrorCode::InvalidMxRecord,
            format!("Invalid MX priority '{}': must be 0-65535", parts[0]),
        )
        .with_field("value")
        .with_value(value)
    })?;

    let target = validate_cname_target(parts[1])?;
    Ok((priority, target))
}

/// Validates an NS record target
pub fn validate_ns_target(target: &str) -> Result<String, ValidationError> {
    validate_dns_name(target, true)
}

/// Validates a TXT record value
pub fn validate_txt_value(value: &str) -> Result<String, ValidationError> {
    if value.len() > 255 {
        return Err(ValidationError::new(
            ValidationErrorCode::InvalidTxtValue,
            format!(
                "TXT record value exceeds 255 characters (got {})",
                value.len()
            ),
        )
        .with_field("value")
        .with_value(value));
    }
    Ok(value.to_string())
}

/// Validates an SRV record value (priority weight port target)
pub fn validate_srv_value(value: &str) -> Result<(u16, u16, u16, String), ValidationError> {
    let parts: Vec<&str> = value.split_whitespace().collect();
    if parts.len() != 4 {
        return Err(ValidationError::new(
            ValidationErrorCode::InvalidSrvRecord,
            "SRV record must have format: 'priority weight port target' (e.g., '10 5 443 server.example.com')",
        ).with_field("value").with_value(value));
    }

    let priority = parts[0].parse::<u16>().map_err(|_| {
        ValidationError::new(
            ValidationErrorCode::InvalidSrvRecord,
            format!("Invalid SRV priority '{}': must be 0-65535", parts[0]),
        )
        .with_field("value")
        .with_value(value)
    })?;

    let weight = parts[1].parse::<u16>().map_err(|_| {
        ValidationError::new(
            ValidationErrorCode::InvalidSrvRecord,
            format!("Invalid SRV weight '{}': must be 0-65535", parts[1]),
        )
        .with_field("value")
        .with_value(value)
    })?;

    let port = parts[2].parse::<u16>().map_err(|_| {
        ValidationError::new(
            ValidationErrorCode::InvalidSrvRecord,
            format!("Invalid SRV port '{}': must be 0-65535", parts[2]),
        )
        .with_field("value")
        .with_value(value)
    })?;

    let target = validate_dns_name(parts[3], true)?;
    Ok((priority, weight, port, target))
}

/// Validates a CAA record value (flags tag value)
pub fn validate_caa_value(value: &str) -> Result<(u8, String, String), ValidationError> {
    let parts: Vec<&str> = value.splitn(3, ' ').collect();
    if parts.len() != 3 {
        return Err(ValidationError::new(
            ValidationErrorCode::InvalidCaaRecord,
            "CAA record must have format: 'flags tag value' (e.g., '0 issue \"letsencrypt.org\"')",
        )
        .with_field("value")
        .with_value(value));
    }

    let flags = parts[0].parse::<u8>().map_err(|_| {
        ValidationError::new(
            ValidationErrorCode::InvalidCaaRecord,
            format!("Invalid CAA flags '{}': must be 0-255", parts[0]),
        )
        .with_field("value")
        .with_value(value)
    })?;

    let tag = parts[1].to_string();
    if tag.is_empty() || tag.len() > 15 || !tag.bytes().all(|byte| byte.is_ascii_alphanumeric()) {
        return Err(ValidationError::new(
            ValidationErrorCode::InvalidCaaRecord,
            "CAA tag must contain 1-15 ASCII letters or digits",
        )
        .with_field("value")
        .with_value(value));
    }

    let value_str = parts[2].trim().to_string();
    if value_str.is_empty() {
        return Err(ValidationError::new(
            ValidationErrorCode::InvalidCaaRecord,
            "CAA value cannot be empty",
        )
        .with_field("value")
        .with_value(value));
    }
    Ok((flags, tag, value_str))
}

fn parse_caa_character_string(input: &str) -> Result<Vec<u8>, ValidationError> {
    let invalid = || {
        ValidationError::new(
            ValidationErrorCode::InvalidCaaRecord,
            "CAA value must be a safe character string",
        )
        .with_field("value")
    };

    if input.starts_with('"') {
        if input.len() < 2 || !input.ends_with('"') {
            return Err(invalid());
        }
        let bytes = input.as_bytes();
        let mut output = Vec::with_capacity(bytes.len().saturating_sub(2));
        let mut index = 1;
        while index < bytes.len() - 1 {
            match bytes[index] {
                b'"' => return Err(invalid()),
                b'\\' => {
                    index += 1;
                    if index >= bytes.len() - 1 {
                        return Err(invalid());
                    }
                    if index + 2 < bytes.len() - 1
                        && bytes[index..index + 3].iter().all(u8::is_ascii_digit)
                    {
                        let code = std::str::from_utf8(&bytes[index..index + 3])
                            .ok()
                            .and_then(|digits| digits.parse::<u16>().ok())
                            .filter(|code| *code <= 255)
                            .ok_or_else(invalid)?;
                        output.push(code as u8);
                        index += 3;
                    } else {
                        output.push(bytes[index]);
                        index += 1;
                    }
                }
                byte => {
                    output.push(byte);
                    index += 1;
                }
            }
        }
        Ok(output)
    } else if input.bytes().any(|byte| {
        byte.is_ascii_whitespace() || matches!(byte, b';' | b'"' | b'\\') || byte.is_ascii_control()
    }) {
        Err(invalid())
    } else {
        Ok(input.as_bytes().to_vec())
    }
}

/// Validates and converts one untrusted API record to normalized typed data.
pub fn validate_record(record: &crate::Record) -> Result<ValidatedRecord, ValidationError> {
    let record_type = record.record_type.to_uppercase();

    if !SUPPORTED_RECORD_TYPES.contains(&record_type.as_str()) {
        return Err(ValidationError::new(
            ValidationErrorCode::UnsupportedRecordType,
            format!(
                "Unsupported record type '{}'. Supported: {}",
                record_type,
                SUPPORTED_RECORD_TYPES.join(", ")
            ),
        )
        .with_field("type")
        .with_value(&record.record_type));
    }

    let normalized_owner = validate_record_name(&record.name)?;
    let name = if normalized_owner == "@" {
        None
    } else {
        Some(validated_name(&normalized_owner)?)
    };
    let data = match record_type.as_str() {
        "A" => ValidatedRData::A(validate_ipv4(&record.value)?),
        "AAAA" => ValidatedRData::Aaaa(validate_ipv6(&record.value)?),
        "CNAME" => {
            let target = validate_cname_target(&record.value)?;
            ValidatedRData::Cname(validated_name(&target)?)
        }
        "MX" => {
            let (priority, target) = validate_mx_value(&record.value)?;
            ValidatedRData::Mx {
                priority,
                target: validated_name(&target)?,
            }
        }
        "NS" => {
            let target = validate_ns_target(&record.value)?;
            ValidatedRData::Ns(validated_name(&target)?)
        }
        "TXT" => {
            let value = validate_txt_value(&record.value)?;
            ValidatedRData::Txt(value.into_bytes())
        }
        "SRV" => {
            let (priority, weight, port, target) = validate_srv_value(&record.value)?;
            ValidatedRData::Srv {
                priority,
                weight,
                port,
                target: validated_name(&target)?,
            }
        }
        "CAA" => {
            let (flags, tag, value) = validate_caa_value(&record.value)?;
            let value = parse_caa_character_string(&value)?;
            ValidatedRData::Caa {
                flags,
                tag: tag.to_ascii_lowercase(),
                value,
            }
        }
        _ => unreachable!(),
    };

    Ok(ValidatedRecord { name, data })
}

/// Validates all records in a zone payload
pub fn validate_zone_payload_with_limits(
    payload: &crate::ZonePayload,
    limits: &RequestLimits,
) -> Result<Vec<ValidatedRecord>, Vec<ValidationError>> {
    if payload.records.len() > limits.max_records_per_zone {
        return Err(vec![ValidationError::new(
            ValidationErrorCode::ResourceLimitExceeded,
            format!(
                "Zone has {} records; maximum is {}",
                payload.records.len(),
                limits.max_records_per_zone
            ),
        )
        .with_field("records")]);
    }

    let mut errors = Vec::new();

    let mut validated = Vec::with_capacity(payload.records.len());
    for (idx, record) in payload.records.iter().enumerate() {
        let mut exceeded_limit = false;
        if record.name.len() > limits.max_record_name_bytes {
            errors.push(
                ValidationError::new(
                    ValidationErrorCode::ResourceLimitExceeded,
                    format!(
                        "Record name exceeds configured limit of {} bytes",
                        limits.max_record_name_bytes
                    ),
                )
                .with_field(&format!("records[{}].name", idx)),
            );
            exceeded_limit = true;
        }
        if record.value.len() > limits.max_record_value_bytes {
            errors.push(
                ValidationError::new(
                    ValidationErrorCode::ResourceLimitExceeded,
                    format!(
                        "Record value exceeds configured limit of {} bytes",
                        limits.max_record_value_bytes
                    ),
                )
                .with_field(&format!("records[{}].value", idx)),
            );
            exceeded_limit = true;
        }
        if exceeded_limit {
            continue;
        }

        match validate_record(record) {
            Ok(record) => validated.push(record),
            Err(e) => {
                let mut err = e.with_field(&format!("records[{}]", idx));
                if err.value.is_none() {
                    err = err.with_value(&record.value);
                }
                errors.push(err);
            }
        }
    }

    if errors.is_empty() {
        errors.extend(validate_record_set(&validated).err().unwrap_or_default());
    }

    if errors.is_empty() {
        Ok(validated)
    } else {
        Err(errors)
    }
}

fn validate_record_set(records: &[ValidatedRecord]) -> Result<(), Vec<ValidationError>> {
    let mut owners: HashMap<String, (usize, usize)> = HashMap::new();
    for record in records {
        let owner = record
            .name
            .as_ref()
            .map(|name| name.to_ascii().to_ascii_lowercase())
            .unwrap_or_else(|| "@".into());
        let (cname_count, other_count) = owners.entry(owner).or_default();
        if matches!(&record.data, ValidatedRData::Cname(_)) {
            *cname_count += 1;
        } else {
            *other_count += 1;
        }
    }

    let mut errors = Vec::new();
    for (owner, (cname_count, other_count)) in owners {
        if cname_count == 0 {
            continue;
        }

        let reason = if owner == "@" {
            Some("CNAME at the zone apex conflicts with the generated SOA and NS records")
        } else if owner == "ns" && other_count == 0 {
            Some("CNAME at ns conflicts with the generated nameserver address record")
        } else if cname_count > 1 || other_count > 0 {
            Some("CNAME cannot coexist with other records at the same owner name")
        } else {
            None
        };

        if let Some(reason) = reason {
            errors.push(
                ValidationError::new(
                    ValidationErrorCode::ConflictingRecords,
                    format!("{} ({})", reason, owner),
                )
                .with_field("records"),
            );
        }
    }

    if errors.is_empty() {
        Ok(())
    } else {
        Err(errors)
    }
}

/// Runs named-checkzone on a zone file for final validation
pub fn validate_zone_file_with_named_checkzone(
    zone_name: &str,
    zone_file_path: &Path,
) -> Result<(), ValidationError> {
    let checkzone_timeout = CHECKZONE_TIMEOUT
        .get()
        .copied()
        .unwrap_or(Duration::from_secs(DEFAULT_CHECKZONE_TIMEOUT_SECS));
    let mut command = Command::new("named-checkzone");
    command.args([zone_name, zone_file_path.to_str().unwrap_or("")]);

    match run_command_with_timeout(&mut command, checkzone_timeout) {
        Ok(status) if status.success() => Ok(()),
        Ok(status) => Err(ValidationError::new(
            ValidationErrorCode::ZoneValidationFailed,
            format!("named-checkzone rejected the zone ({})", status),
        )
        .with_field("zone")
        .with_value(zone_name)),
        Err(CommandFailure::Unavailable) => {
            tracing::warn!("named-checkzone introuvable — validation du fichier de zone ignorée");
            Ok(())
        }
        Err(CommandFailure::TimedOut) => Err(ValidationError::new(
            ValidationErrorCode::ZoneValidationTimeout,
            "named-checkzone timed out",
        )
        .with_field("zone")
        .with_value(zone_name)),
        Err(CommandFailure::Spawn) => Err(ValidationError::new(
            ValidationErrorCode::ZoneValidationFailed,
            "failed to start named-checkzone",
        )
        .with_field("zone")
        .with_value(zone_name)),
    }
}

#[derive(Debug, PartialEq, Eq)]
enum CommandFailure {
    Unavailable,
    TimedOut,
    Spawn,
}

/// Attend un processus avec une échéance fixe et jette sa sortie : l'API ne
/// capture ni ne met en mémoire les diagnostics potentiellement volumineux.
fn run_command_with_timeout(
    command: &mut Command,
    timeout: Duration,
) -> Result<ExitStatus, CommandFailure> {
    let mut child = command
        .stdout(Stdio::null())
        .stderr(Stdio::null())
        .spawn()
        .map_err(|error| {
            if error.kind() == io::ErrorKind::NotFound {
                CommandFailure::Unavailable
            } else {
                CommandFailure::Spawn
            }
        })?;
    wait_with_timeout(&mut child, timeout)
}

fn wait_with_timeout(child: &mut Child, timeout: Duration) -> Result<ExitStatus, CommandFailure> {
    let deadline = Instant::now() + timeout;
    loop {
        match child.try_wait() {
            Ok(Some(status)) => return Ok(status),
            Ok(None) if Instant::now() < deadline => thread::sleep(Duration::from_millis(10)),
            Ok(None) => {
                let _ = child.kill();
                let _ = child.wait();
                return Err(CommandFailure::TimedOut);
            }
            Err(_) => {
                let _ = child.kill();
                let _ = child.wait();
                return Err(CommandFailure::Spawn);
            }
        }
    }
}

/// Generates a Problem Details response for multiple validation errors
pub fn validation_errors_to_problem_details(
    errors: &[ValidationError],
    instance: Option<&str>,
) -> ProblemDetails {
    let first = &errors[0];
    let mut ext = std::collections::HashMap::new();
    ext.insert("errors".to_string(), serde_json::to_value(errors).unwrap());
    ext.insert(
        "error_count".to_string(),
        serde_json::Value::Number(errors.len().into()),
    );

    let title = if first.code.status_code() == 503 {
        "Service Unavailable"
    } else {
        "Validation Failed"
    };
    ProblemDetails::new(first.code.status_code(), title)
        .with_detail(&format!("{} validation error(s)", errors.len()))
        .with_instance(instance.unwrap_or(""))
        .with_extensions(ext)
}

